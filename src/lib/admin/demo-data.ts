export function normalizeState(
  partial: Partial<AdminDemoState>,
): AdminDemoState {
  const seed = createSeedState();
  return {
    ...seed,
    ...partial,
    tenants: partial.tenants?.length ? partial.tenants : seed.tenants,
    shards: partial.shards?.length ? partial.shards : seed.shards,
    migrations: partial.migrations?.length
      ? partial.migrations
      : seed.migrations,
    enclaves: partial.enclaves?.length ? partial.enclaves : seed.enclaves,
    rootKeys: partial.rootKeys?.length ? partial.rootKeys : seed.rootKeys,
    custodians: partial.custodians?.length
      ? partial.custodians
      : seed.custodians,
    tariffs: partial.tariffs?.length ? partial.tariffs : seed.tariffs,
    quotas: partial.quotas?.length ? partial.quotas : seed.quotas,
    clearing: partial.clearing?.length ? partial.clearing : seed.clearing,
    events: partial.events?.length ? partial.events : seed.events,
    kpis: partial.kpis ? { ...seed.kpis, ...partial.kpis } : seed.kpis,
    economics: partial.economics
      ? { ...seed.economics, ...partial.economics }
      : seed.economics,
  };
}

export function tenantById(state: AdminDemoState, id: string | null) {
  if (!id) return undefined;
  return state.tenants.find((t) => t.id === id);
}
